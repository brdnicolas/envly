// Extends app.json. The product extractor (share-extension/preprocess.js) is used twice:
//  - injected into the iOS share extension (runs inside the shared Safari page);
//  - bundled into the app for the on-device page reader (src/lib/page-extractor.generated.ts).
const fs = require('fs');
const path = require('path');

const extractor = fs.readFileSync(path.join(__dirname, 'share-extension/preprocess.js'), 'utf8');

const generated = path.join(__dirname, 'src/lib/page-extractor.generated.ts');
const content = `// AUTO-GENERATED by app.config.js from share-extension/preprocess.js. Do not edit.\nexport const PAGE_EXTRACTOR_JS = ${JSON.stringify(extractor)};\n`;
if (!fs.existsSync(generated) || fs.readFileSync(generated, 'utf8') !== content) fs.writeFileSync(generated, content);

// Android push goes through Firebase Cloud Messaging: add google-services.json (Firebase console →
// project settings → Android app fr.envly.app) next to this file and it's picked up automatically.
const googleServices = path.join(__dirname, 'google-services.json');

module.exports = ({ config }) => ({
  ...config,
  android: {
    ...config.android,
    ...(fs.existsSync(googleServices) && { googleServicesFile: './google-services.json' }),
  },
  plugins: config.plugins.map((p) =>
    Array.isArray(p) && p[0] === 'expo-share-intent' ? [p[0], { ...p[1], preprocessorInjectJS: extractor }] : p
  ),
});
